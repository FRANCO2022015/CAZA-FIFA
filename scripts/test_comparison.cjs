const points=buildTimeline([row(4,2,6,120),row(1,1,1,100),row(3,2,3,50),row(2,2,2,5)],1,2,'goles');
assert.equal(points[0].b,null);assert.equal(points[2].a,100);
assert.equal(firstOvertake(points).elapsed,4*86400000);
